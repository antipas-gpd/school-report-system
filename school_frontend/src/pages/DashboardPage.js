import React, { useEffect, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { useAuth } from '../context/AuthContext';
import { studentsAPI, reportsAPI, feesAPI } from '../api/services';

// ── Admin Dashboard ───────────────────────────────────────────────────
function AdminDashboard() {
  const [reports, setReports]   = useState([]);
  const [students, setStudents] = useState([]);
  const [loading, setLoading]   = useState(true);
  const navigate = useNavigate();

  useEffect(() => {
    Promise.all([reportsAPI.list(), studentsAPI.list()])
      .then(([r, s]) => {
        setReports(r.data.results || r.data);
        setStudents(s.data.results || s.data);
      })
      .finally(() => setLoading(false));
  }, []);

  const approve = async (id) => {
    await reportsAPI.approve(id);
    setReports(prev => prev.map(r => r.id === id ? { ...r, approved: true } : r));
  };

  if (loading) return <div className="spinner" />;

  const pending  = reports.filter(r => !r.approved).length;
  const approved = reports.filter(r => r.approved).length;

  return (
    <>
      <div className="card-grid">
        <div className="stat-card">
          <div className="stat-label">Total Students</div>
          <div className="stat-value">{students.length}</div>
        </div>
        <div className="stat-card">
          <div className="stat-label">Reports Generated</div>
          <div className="stat-value">{reports.length}</div>
        </div>
        <div className="stat-card">
          <div className="stat-label">Pending Approval</div>
          <div className="stat-value" style={{ color: 'var(--warning)' }}>{pending}</div>
        </div>
        <div className="stat-card">
          <div className="stat-label">Approved</div>
          <div className="stat-value" style={{ color: 'var(--success)' }}>{approved}</div>
        </div>
      </div>

      <div className="card">
        <div className="page-header" style={{ marginBottom: 16 }}>
          <h3>Recent Reports</h3>
          <button className="btn btn-ghost btn-sm" onClick={() => navigate('/reports')}>
            View all
          </button>
        </div>
        <div className="table-wrap">
          <table>
            <thead>
              <tr>
                <th>Student</th>
                <th>Term</th>
                <th>Generated by</th>
                <th>Status</th>
                <th>Action</th>
              </tr>
            </thead>
            <tbody>
              {reports.slice(0, 8).map(r => (
                <tr key={r.id}>
                  <td>{r.student_name}</td>
                  <td>{r.term}</td>
                  <td style={{ color: 'var(--text-2)', fontFamily: 'var(--mono)', fontSize: '.8rem' }}>
                    {r.generated_by_name}
                  </td>
                  <td>
                    <span className={`badge ${r.approved ? 'badge-green' : 'badge-yellow'}`}>
                      {r.approved ? 'Approved' : 'Pending'}
                    </span>
                  </td>
                  <td>
                    {!r.approved && (
                      <button className="btn btn-success btn-sm" onClick={() => approve(r.id)}>
                        Approve
                      </button>
                    )}
                  </td>
                </tr>
              ))}
              {reports.length === 0 && (
                <tr><td colSpan={5} style={{ textAlign: 'center', color: 'var(--text-3)', padding: 32 }}>
                  No reports yet
                </td></tr>
              )}
            </tbody>
          </table>
        </div>
      </div>
    </>
  );
}

