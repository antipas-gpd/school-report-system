import React, { useEffect, useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { reportsAPI, studentsAPI } from '../api/services';
import { useAuth } from '../context/AuthContext';

export default function ReportsPage() {
  const { user }        = useAuth();
  const [searchParams]  = useSearchParams();
  const [reports,   setReports]   = useState([]);
  const [students,  setStudents]  = useState([]);
  const [selected,  setSelected]  = useState(searchParams.get('generate') || '');
  const [term,      setTerm]      = useState('Term 1');
  const [report,    setReport]    = useState(null);
  const [loading,   setLoading]   = useState(false);
  const [listLoading, setListLoading] = useState(true);
  const [comment,   setComment]   = useState('');
  const [msg,       setMsg]       = useState('');

  useEffect(() => {
    Promise.all([reportsAPI.list(), studentsAPI.list()])
      .then(([r, s]) => {
        setReports(r.data.results || r.data);
        setStudents(s.data.results || s.data);
      })
      .finally(() => setListLoading(false));

    if (searchParams.get('generate')) generateReport();
  }, []);

  const generateReport = async (sid, t) => {
    const studentId = sid || selected;
    const termVal   = t   || term;
    if (!studentId) return;
    setLoading(true);
    setReport(null);
    setMsg('');
    try {
      const res = await reportsAPI.generate(studentId, termVal);
      setReport(res.data);
      // Refresh list
      reportsAPI.list().then(r => setReports(r.data.results || r.data));
    } catch (err) {
      setMsg(err.response?.data?.error || 'Failed to generate report.');
    } finally {
      setLoading(false);
    }
  };

  const approve = async (id) => {
    await reportsAPI.approve(id);
    setMsg('Report approved!');
    if (report?.report_id === id) setReport(r => ({ ...r, approved: true }));
    setReports(prev => prev.map(r => r.id === id ? { ...r, approved: true } : r));
  };

  const saveComment = async () => {
    if (!report || !comment.trim()) return;
    await reportsAPI.comment(report.report_id, comment);
    setReport(r => ({ ...r, teacher_comment: comment }));
    setMsg('Comment saved!');
  };

  const gradeColor = g => ({ A: 'var(--success)', B: 'var(--accent)', C: 'var(--warning)', D: 'var(--danger)' }[g]);

  return (
    <>
      <div className="page-header">
        <h1>Reports</h1>
      </div>

      {msg && <div className="alert alert-success" onClick={() => setMsg('')}>{msg}</div>}

      {/* Generate section (teacher/admin) */}
      {(user?.role === 'teacher' || user?.role === 'admin') && (
        <div className="card" style={{ marginBottom: 24 }}>
          <h3 style={{ marginBottom: 16 }}>Generate Report</h3>
          <div style={{ display: 'flex', gap: 12, flexWrap: 'wrap', alignItems: 'flex-end' }}>
            <div className="form-group" style={{ margin: 0 }}>
              <label className="form-label">Student</label>
              <select className="form-select" value={selected} onChange={e => setSelected(e.target.value)} style={{ minWidth: 220 }}>
                <option value="">Select student…</option>
                {students.map(s => <option key={s.id} value={s.id}>{s.full_name} ({s.student_id})</option>)}
              </select>
            </div>
            <div className="form-group" style={{ margin: 0 }}>
              <label className="form-label">Term</label>
              <select className="form-select" value={term} onChange={e => setTerm(e.target.value)}>
                <option>Term 1</option><option>Term 2</option><option>Term 3</option>
              </select>
            </div>
            <button className="btn btn-primary" onClick={() => generateReport(selected, term)} disabled={!selected || loading}>
              {loading ? 'Generating…' : '⚡ Generate'}
            </button>
          </div>
        </div>
      )}

      {/* Generated report detail */}
      {loading && <div className="spinner" />}

      {report && !loading && (
        <div className="card" style={{ marginBottom: 24 }}>
          {/* Header */}
          <div className="report-header">
            <div>
              <h2>{report.student_name}</h2>
              <p>{report.class_name} &middot; {report.term} &middot; Generated by {report.generated_by}</p>
            </div>
            <div className="report-meta">
              <span className={`badge ${report.approved ? 'badge-green' : 'badge-yellow'}`}>
                {report.approved ? '✓ Approved' : 'Pending'}
              </span>
              <span className={`badge ${report.fees_fully_paid ? 'badge-green' : 'badge-red'}`}>
                Fees {report.fees_fully_paid ? 'Paid' : 'Outstanding'}
              </span>
            </div>
          </div>

          {/* Stats */}
          <div className="report-stats">
            {[
              { label: 'Average',  value: `${report.average_score}%` },
              { label: 'Total',    value: report.total_score },
              { label: 'Attendance', value: `${report.attendance_pct}%` },
              { label: 'Present',  value: `${report.attendance_present}/${report.attendance_total}` },
              { label: 'Fees Balance', value: `$${report.fees_balance}` },
            ].map(s => (
              <div className="report-stat" key={s.label}>
                <div className="rs-label">{s.label}</div>
                <div className="rs-value">{s.value}</div>
              </div>
            ))}
          </div>

          <div className="divider" />

          {/* Marks table */}
          <h3 style={{ marginBottom: 12 }}>Subject Results</h3>
          <div className="table-wrap" style={{ marginBottom: 20 }}>
            <table>
              <thead><tr><th>Subject</th><th>Code</th><th>Score</th><th>Grade</th></tr></thead>
              <tbody>
                {report.marks?.map((m, i) => (
                  <tr key={i}>
                    <td>{m.subject_name}</td>
                    <td style={{ fontFamily: 'var(--mono)', fontSize: '.8rem', color: 'var(--text-2)' }}>{m.subject_code}</td>
                    <td>{m.score}</td>
                    <td><span style={{ color: gradeColor(m.grade), fontWeight: 700 }}>{m.grade}</span></td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          {/* AI Comment */}
          {report.ai_comment && (
            <div style={{ marginBottom: 16 }}>
              <h3 style={{ marginBottom: 8 }}>AI Comment</h3>
              <div className="comment-box">{report.ai_comment}</div>
            </div>
          )}

          {/* Teacher comment */}
          {(user?.role === 'teacher' || user?.role === 'admin') && (
            <div style={{ marginBottom: 16 }}>
              <h3 style={{ marginBottom: 8 }}>Teacher's Comment</h3>
              <textarea
                className="form-input"
                rows={3}
                value={comment || report.teacher_comment}
                onChange={e => setComment(e.target.value)}
                placeholder="Add a comment…"
                style={{ resize: 'vertical' }}
              />
              <button className="btn btn-ghost btn-sm" onClick={saveComment} style={{ marginTop: 8 }}>
                Save Comment
              </button>
            </div>
          )}

          {/* Approve button (admin only) */}
          {user?.role === 'admin' && !report.approved && (
            <button className="btn btn-success" onClick={() => approve(report.report_id)}>
              ✓ Approve Report
            </button>
          )}
        </div>
      )}

      {/* Reports list */}
      <div className="card">
        <h3 style={{ marginBottom: 16 }}>All Reports</h3>
        {listLoading ? <div className="spinner" /> : (
          <div className="table-wrap">
            <table>
              <thead>
                <tr>
                  <th>Student</th>
                  <th>Term</th>
                  <th>Generated by</th>
                  <th>Date</th>
                  <th>Status</th>
                  {user?.role === 'admin' && <th>Action</th>}
                </tr>
              </thead>
              <tbody>
                {reports.map(r => (
                  <tr key={r.id}>
                    <td><strong>{r.student_name}</strong></td>
                    <td>{r.term}</td>
                    <td style={{ color: 'var(--text-2)', fontFamily: 'var(--mono)', fontSize: '.8rem' }}>
                      {r.generated_by_name}
                    </td>
                    <td style={{ color: 'var(--text-2)', fontSize: '.85rem' }}>
                      {new Date(r.created_at).toLocaleDateString()}
                    </td>
                    <td>
                      <span className={`badge ${r.approved ? 'badge-green' : 'badge-yellow'}`}>
                        {r.approved ? 'Approved' : 'Pending'}
                      </span>
                    </td>
                    {user?.role === 'admin' && (
                      <td>
                        {!r.approved && (
                          <button className="btn btn-success btn-sm" onClick={() => approve(r.id)}>
                            Approve
                          </button>
                        )}
                      </td>
                    )}
                  </tr>
                ))}
                {reports.length === 0 && (
                  <tr><td colSpan={6}>
                    <div className="empty"><div className="empty-icon">📄</div><p>No reports yet.</p></div>
                  </td></tr>
                )}
              </tbody>
            </table>
          </div>
        )}
      </div>
    </>
  );
}
